function build() {
  const pages = [hubPage(), gtPage()];
  for (const key of DATA.ORDER) {
    pages.push(branchPage(key));
    for (const job of DATA.BRANCHES[key].jobs) if (job.featured) pages.push(jobPage(key, job));
  }
  return pages.map(({ file, html }) => ({ file, html: syncPage(file, html) }));
}

function files() {
  return build().map((p) => p.file);
}

// sitemap.xml keeps a generated block between <!-- job-pages --> markers.
function sitemap(current, pages) {
  const noindex = new Set(['my-options.html']);
  const entries = pages.filter((p) => !noindex.has(p.file)).map((p) => {
    const prio = p.file.startsWith('jobs/') ? '0.6' : '0.8';
    return `  <url>
    <loc>${SITE}${p.file}</loc>
    <lastmod>${MODIFIED}</lastmod>
    <changefreq>monthly</changefreq>
    <priority>${prio}</priority>
  </url>`;
  }).join('\n');
  const block = `  <!-- job-pages (generated by scripts/build-job-pages.js) -->\n${entries}\n  <!-- /job-pages -->`;
  const marked = /  <!-- job-pages[\s\S]*?<!-- \/job-pages -->/;
  if (marked.test(current)) return current.replace(marked, block);
  return current.replace('</urlset>', `${block}\n</urlset>`);
}

