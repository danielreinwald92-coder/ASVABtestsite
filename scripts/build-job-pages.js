function compositeTable(key, b) {
  if (!b.composites) return '';
  const rows = Object.entries(b.composites).map(([c, name]) => {
    const parts = compositeParts(key, c);
    return `          <tr><th scope="row">${esc(c)}</th><td>${esc(name)}</td><td>${esc(formulaText(Object.keys(parts), parts))}</td></tr>`;
  }).join('\n');
  return `
      <table class="score-table">
        <thead><tr><th scope="col">Code</th><th scope="col">Score</th><th scope="col">Made from</th></tr></thead>
        <tbody>
${rows}
        </tbody>
      </table>`;
}

