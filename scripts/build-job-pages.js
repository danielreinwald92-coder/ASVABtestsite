//   jobs/<branch>-<code>-<slug>.html     one page per featured job
//   asvab-gt-score.html                  GT score explainer + jobs that use GT
// Job pages live in jobs/ and use <base href="/"> so the shared chrome and
// asset links stay root-relative (never use #fragment links on those pages).
//
//   node scripts/build-job-pages.js          # write the pages
//   node scripts/build-job-pages.js --check  # exit 1 if any page is stale
//
// Re-run after editing js/job-requirements.js or the copy below;
// tests/unit/job-pages.test.js fails when pages drift.
