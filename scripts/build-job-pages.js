// ---------------------------------------------------------------- job pages
function relatedJobs(key, job) {
  const b = DATA.BRANCHES[key];
  const pool = b.jobs.filter((j) => j.featured && j.code !== job.code);
  const same = pool.filter((j) => j.category === job.category);
  const comps = new Set(M.composites(job.rule));
  const shared = pool.filter((j) => !same.includes(j) && M.composites(j.rule).some((c) => comps.has(c)));
  const rest = pool.filter((j) => !same.includes(j) && !shared.includes(j));
  return same.concat(shared, rest).slice(0, 5);
}

function scoreParts(key, job) {
  const seen = new Set();
  const items = [];
  for (const path of job.rule) {
    for (const t of path) {
      if (t.c && !seen.has('c:' + t.c)) {
        seen.add('c:' + t.c);
        const parts = compositeParts(key, t.c);
        const name = DATA.BRANCHES[key].composites[t.c];
        items.push(`<li><strong>${esc(t.c)} (${esc(name)})</strong> = ${esc(formulaText(Object.keys(parts), parts))}. Study: ${sectionLinks(Object.keys(parts)).join(', ')}</li>`);
      } else if (t.sum) {
        const secs = Object.keys(t.sum).filter((k) => !M.UNTESTED_INPUTS.includes(k));
        const k = 's:' + secs.join('+');
        if (secs.length > 1 && !seen.has(k)) {
          seen.add(k);
          items.push(`<li><strong>${esc(M.termText(t).replace(/ = \d+$/, ''))}</strong>: ${secs.map((s) => esc(SECTION_NAME[s] || s)).join(', ')}. Study: ${sectionLinks(secs).join(', ')}</li>`);
        }
      }
    }
  }
  return items;
}

