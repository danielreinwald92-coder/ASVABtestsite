if (require.main === module) {
  const check = process.argv.includes('--check');
  let stale = 0;
  const built = build();
  const expected = new Set(built.map((p) => p.file));
  for (const { file, html } of built) {
    const target = path.join(root, file);
    const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
    if (current === html) continue;
    if (check) { console.error(`stale: ${file}`); stale++; } else {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, html);
      console.log(`wrote ${file}`);
    }
  }
  const mapFile = path.join(root, 'sitemap.xml');
  const mapNow = fs.readFileSync(mapFile, 'utf8');
  const mapNext = sitemap(mapNow, built);
  if (mapNow !== mapNext) {
    if (check) { console.error('stale: sitemap.xml'); stale++; } else { fs.writeFileSync(mapFile, mapNext); console.log('wrote sitemap.xml'); }
  }
  // Job pages removed from the data must not linger in jobs/.
  const jobsDir = path.join(root, 'jobs');
  if (fs.existsSync(jobsDir)) {
    for (const f of fs.readdirSync(jobsDir)) {
      if (expected.has(`jobs/${f}`)) continue;
      if (check) { console.error(`orphan: jobs/${f}`); stale++; } else { fs.unlinkSync(path.join(jobsDir, f)); console.log(`removed jobs/${f}`); }
    }
  }
  if (check && stale) process.exit(1);
}
