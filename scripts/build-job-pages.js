function article(title, description, file) {
  return {
    '@context': 'https://schema.org',
    '@type': 'Article',
    headline: title,
    description,
    mainEntityOfPage: SITE + file,
    datePublished: PUBLISHED,
    dateModified: MODIFIED,
    author: { '@type': 'Organization', name: 'Mission ASVAB', url: SITE },
    publisher: { '@type': 'Organization', name: 'Mission ASVAB', url: SITE },
  };
}

function breadcrumbs(items) {
  return {
    '@context': 'https://schema.org',
    '@type': 'BreadcrumbList',
    itemListElement: items.map(([name, file], i) => ({ '@type': 'ListItem', position: i + 1, name, item: SITE + file })),
  };
}

