const REQUIRED_SCRIPTS = {
  full: ['js/year.js', 'js/mobile-menu.js', 'js/site-nav.js'],
  footer: ['js/year.js', 'js/site-nav.js'],
};

// Replace a marked block, or (first run) the legacy markup it supersedes.
function replaceNav(src, page) {
  const block = renderNav(page);
  const marked = /<!-- site-nav[\s\S]*?<!-- \/site-nav -->/;
  if (marked.test(src)) return src.replace(marked, block);
  const navStart = src.indexOf('<nav');
  if (navStart < 0) throw new Error(`${page}: no <nav> to migrate`);
  let end = src.indexOf('</nav>', navStart) + '</nav>'.length;
  const rest = src.slice(end);
  const mm = rest.match(/^\s*<div class="mobile-menu"/);
  if (mm) {
    let i = end + rest.indexOf('<div class="mobile-menu"');
    let depth = 0;
    const re = /<div\b|<\/div>/g;
    re.lastIndex = i;
    let m;
    while ((m = re.exec(src))) {
      depth += m[0] === '</div>' ? -1 : 1;
      if (depth === 0) { end = m.index + '</div>'.length; break; }
    }
  }
  return src.slice(0, navStart) + block + src.slice(end);
}

function replaceFooter(src, page) {
  const block = renderFooter(page);
  const marked = /<!-- site-footer[\s\S]*?<!-- \/site-footer -->/;
  if (marked.test(src)) return src.replace(marked, block);
  const start = src.indexOf('<footer');
  if (start >= 0) {
    const end = src.indexOf('</footer>', start) + '</footer>'.length;
    return src.slice(0, start) + block + src.slice(end);
  }
  return src.replace(/(\n\s*<script)/, `\n  ${block}\n$1`);
}

function ensureScripts(src, kind) {
  for (const s of REQUIRED_SCRIPTS[kind]) {
    if (src.includes(`src="${s}"`)) continue;
    src = src.replace('</body>', `  <script src="${s}"></script>\n</body>`);
  }
  return src;
}

function syncPage(page, src) {
  const kind = PAGES[page] || (page.startsWith('jobs/') ? 'full' : undefined);
  if (kind === 'full') src = replaceNav(src, page);
  src = replaceFooter(src, page);
  return ensureScripts(src, kind);
}

module.exports = { renderNav, renderFooter, syncPage, PAGES, GUIDES, RESOURCES, PRACTICE };

if (require.main === module) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const page of Object.keys(PAGES)) {
    const file = path.join(root, page);
    if (!fs.existsSync(file)) { console.error(`missing page: ${page}`); stale++; continue; }
    const src = fs.readFileSync(file, 'utf8');
    const out = syncPage(page, src);
    if (out === src) continue;
    if (check) { console.error(`stale chrome: ${page}`); stale++; } else { fs.writeFileSync(file, out); console.log(`synced ${page}`); }
  }
  if (check && stale) process.exit(1);
}
